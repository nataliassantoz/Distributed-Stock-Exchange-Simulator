CREATE TABLE usuario (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    nome VARCHAR(150) NOT NULL,
    email VARCHAR(254) NOT NULL,
    senha_hash VARCHAR(255) NOT NULL,
    tipo VARCHAR(10) NOT NULL,
    saldo_caixa NUMERIC(19,2) NOT NULL DEFAULT 0,
    saldo_reservado NUMERIC(19,2) NOT NULL DEFAULT 0,
    CONSTRAINT pk_usuario PRIMARY KEY (id),
    CONSTRAINT uk_usuario_email UNIQUE (email),
    CONSTRAINT ck_usuario_tipo CHECK (tipo IN ('HUMANO', 'AGENTE')),
    CONSTRAINT ck_usuario_saldo_caixa CHECK (saldo_caixa >= 0),
    CONSTRAINT ck_usuario_saldo_reservado CHECK (saldo_reservado >= 0 AND saldo_reservado <= saldo_caixa)
);

CREATE TABLE ativo (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    ticker VARCHAR(20) NOT NULL,
    nome VARCHAR(150) NOT NULL,
    preco_inicial NUMERIC(19,2) NOT NULL,
    preco_atual NUMERIC(19,2) NOT NULL,
    quantidade_total INTEGER NOT NULL,
    CONSTRAINT pk_ativo PRIMARY KEY (id),
    CONSTRAINT uk_ativo_ticker UNIQUE (ticker),
    CONSTRAINT ck_ativo_preco_inicial CHECK (preco_inicial > 0),
    CONSTRAINT ck_ativo_preco_atual CHECK (preco_atual > 0),
    CONSTRAINT ck_ativo_quantidade_total CHECK (quantidade_total > 0)
);

CREATE TABLE carteira (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    usuario_id BIGINT NOT NULL,
    CONSTRAINT pk_carteira PRIMARY KEY (id),
    CONSTRAINT uk_carteira_usuario UNIQUE (usuario_id),
    CONSTRAINT fk_carteira_usuario FOREIGN KEY (usuario_id) REFERENCES usuario (id) ON DELETE RESTRICT
);

-- PKs e constraints UNIQUE criam índices B-tree no PostgreSQL, incluindo
-- carteira.usuario_id para consultas pelo proprietário e validação da FK.
