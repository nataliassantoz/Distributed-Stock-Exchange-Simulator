CREATE TABLE ordem (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    usuario_id BIGINT NOT NULL,
    ativo_id BIGINT NOT NULL,
    tipo VARCHAR(6) NOT NULL,
    quantidade_original INTEGER NOT NULL,
    quantidade_restante INTEGER NOT NULL,
    preco_limite NUMERIC(19,2) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDENTE',
    criada_em TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_ordem PRIMARY KEY (id),
    CONSTRAINT fk_ordem_usuario FOREIGN KEY (usuario_id) REFERENCES usuario (id) ON DELETE RESTRICT,
    CONSTRAINT fk_ordem_ativo FOREIGN KEY (ativo_id) REFERENCES ativo (id) ON DELETE RESTRICT,
    CONSTRAINT ck_ordem_tipo CHECK (tipo IN ('COMPRA', 'VENDA')),
    CONSTRAINT ck_ordem_quantidade CHECK (quantidade_original > 0),
    CONSTRAINT ck_ordem_restante CHECK (quantidade_restante >= 0 AND quantidade_restante <= quantidade_original),
    CONSTRAINT ck_ordem_preco CHECK (preco_limite > 0),
    CONSTRAINT ck_ordem_status CHECK (status IN ('PENDENTE'))
);

CREATE INDEX ix_ordem_usuario ON ordem (usuario_id);
CREATE INDEX ix_ordem_processamento ON ordem (status, ativo_id, tipo, preco_limite, criada_em, id);
